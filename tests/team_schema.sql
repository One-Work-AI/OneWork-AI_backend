-- PostgreSQL 16+ 신규 구축용. 기존 SQLite 데이터 이전 스크립트가 아닙니다.
BEGIN;
CREATE SCHEMA cs_chatbot;
SET LOCAL search_path TO cs_chatbot, public;

CREATE TABLE customer (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 phone TEXT,
 email TEXT,
 privacy_agreed BOOLEAN NOT NULL DEFAULT FALSE,
 privacy_agreed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE admin_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 login_id TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 name TEXT NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE product (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_name TEXT NOT NULL,
 description TEXT,
 category TEXT,
 brand TEXT,
 price BIGINT NOT NULL CHECK (price >= 0),
 stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
 status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','SOLD_OUT','DISCONTINUED')),
 is_event BOOLEAN NOT NULL DEFAULT FALSE,
 event_name TEXT,
 event_start_date DATE,
 event_end_date DATE,
 event_discount_rate INTEGER CHECK (event_discount_rate BETWEEN 0 AND 100),
 image_url TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 CHECK (event_end_date IS NULL OR event_start_date IS NULL OR event_end_date >= event_start_date)
);
CREATE TABLE orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_no TEXT NOT NULL UNIQUE,
 customer_id BIGINT NOT NULL REFERENCES customer(id),
 order_date TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PAID','PREPARING','SHIPPED','DELIVERED','CANCELED')),
 total_amount BIGINT NOT NULL CHECK (total_amount >= 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(id, customer_id)
);
CREATE TABLE order_item (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES orders(id),
 product_id BIGINT NOT NULL REFERENCES product(id),
 product_name TEXT NOT NULL,
 product_option TEXT,
 quantity INTEGER NOT NULL CHECK (quantity > 0),
 price BIGINT NOT NULL CHECK (price >= 0),
 discount_amount BIGINT NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
 amount BIGINT NOT NULL CHECK (amount >= 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 CHECK (amount = quantity * price - discount_amount)
);
-- MVP: 주문 하나당 배송/결제 하나. 분할 배송·결제 재시도는 확장 대상.
CREATE TABLE shipping (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
 recipient_name TEXT NOT NULL,
 recipient_phone TEXT,
 address TEXT NOT NULL,
 delivery_city TEXT,
 delivery_country TEXT NOT NULL DEFAULT 'KR',
 shipping_method TEXT,
 carrier_name TEXT,
 tracking_number TEXT,
 estimated_delivery_date DATE,
 status TEXT NOT NULL DEFAULT 'PREPARING' CHECK (status IN ('PREPARING','SHIPPING','DELIVERED','CANCELED')),
 shipped_at TIMESTAMPTZ,
 delivered_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE payment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
 payment_method TEXT NOT NULL CHECK (payment_method IN ('BANK_TRANSFER','CREDIT_CARD','EASY_PAY')),
 payment_status TEXT NOT NULL DEFAULT 'PENDING' CHECK (payment_status IN ('PENDING','COMPLETED','FAILED','CANCELED','REFUNDED')),
 amount BIGINT NOT NULL CHECK (amount >= 0),
 transaction_id TEXT UNIQUE,
 paid_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE refund (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
 refund_reason TEXT NOT NULL,
 refund_amount BIGINT NOT NULL CHECK (refund_amount > 0),
 refund_status TEXT NOT NULL DEFAULT 'REQUESTED' CHECK (refund_status IN ('REQUESTED','PROCESSING','COMPLETED','REJECTED')),
 requested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 processed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE conversation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES customer(id),
 title TEXT,
 status TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 closed_at TIMESTAMPTZ,
 UNIQUE(id, customer_id)
);
-- inquiry 1행 = 고객 메시지 1개. conversation 하나에 여러 inquiry.
CREATE TABLE inquiry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inquiry_no TEXT NOT NULL UNIQUE,
 conversation_id BIGINT NOT NULL,
 customer_id BIGINT NOT NULL REFERENCES customer(id),
 order_id BIGINT,
 content TEXT NOT NULL CHECK (length(trim(content)) > 0),
 detected_language TEXT NOT NULL DEFAULT 'unknown',
 status TEXT NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED','PROCESSING','REVIEW_PENDING','AUTO_ANSWERED','COMPLETED','FAILED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 FOREIGN KEY (conversation_id, customer_id) REFERENCES conversation(id, customer_id),
 FOREIGN KEY (order_id, customer_id) REFERENCES orders(id, customer_id)
);
CREATE TABLE ai_analysis (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inquiry_id BIGINT NOT NULL REFERENCES inquiry(id),
 category TEXT NOT NULL,
 intent TEXT NOT NULL,
 category_confidence NUMERIC(6,5) CHECK (category_confidence BETWEEN 0 AND 1),
 intent_confidence NUMERIC(6,5) CHECK (intent_confidence BETWEEN 0 AND 1),
 urgency TEXT NOT NULL DEFAULT 'NORMAL' CHECK (urgency IN ('NORMAL','CAUTION','URGENT')),
 urgency_confidence NUMERIC(6,5) CHECK (urgency_confidence BETWEEN 0 AND 1),
 auto_response_allowed BOOLEAN NOT NULL DEFAULT FALSE,
 decision_reason TEXT,
 decision_rule_version TEXT NOT NULL,
 analysis_model TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(id, inquiry_id)
);
-- 정책 버전별 새 행. 기존 정책/청크를 수정하지 않아야 과거 근거가 보존됩니다.
CREATE TABLE policy_document (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 document_key TEXT NOT NULL,
 title TEXT NOT NULL,
 category TEXT,
 content TEXT NOT NULL,
 source_file TEXT,
 version TEXT NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(document_key, version)
);
CREATE UNIQUE INDEX uq_policy_active ON policy_document(document_key) WHERE is_active;
CREATE TABLE policy_chunk (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 policy_document_id BIGINT NOT NULL REFERENCES policy_document(id),
 chunk_text TEXT NOT NULL,
 chunk_order INTEGER NOT NULL CHECK (chunk_order >= 0),
 category TEXT,
 section TEXT,
 page_number INTEGER CHECK (page_number > 0),
 embedding_id TEXT,
 vector_collection TEXT,
 embedding_model TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(policy_document_id, chunk_order),
 UNIQUE(vector_collection, embedding_id)
);
CREATE TABLE ai_response (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inquiry_id BIGINT NOT NULL REFERENCES inquiry(id),
 analysis_id BIGINT NOT NULL,
 response_text TEXT NOT NULL CHECK (length(btrim(response_text)) > 0),
 response_language TEXT NOT NULL,
 generation_model TEXT NOT NULL,
 adapter_version TEXT,
 prompt_version TEXT NOT NULL,
 -- LLM이 만든 원문은 response_text, 전송할 최종 문구는 final_response_text.
 final_response_text TEXT,
 status TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','REVIEW_PENDING','APPROVED','REJECTED','SENT')),
 sent_automatically BOOLEAN NOT NULL DEFAULT FALSE,
 sent_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 FOREIGN KEY (analysis_id, inquiry_id) REFERENCES ai_analysis(id, inquiry_id),
 CHECK ((status = 'SENT' AND sent_at IS NOT NULL AND final_response_text IS NOT NULL AND length(trim(final_response_text)) > 0)
     OR (status <> 'SENT' AND sent_at IS NULL AND NOT sent_automatically))
);
CREATE UNIQUE INDEX uq_sent_response ON ai_response(inquiry_id) WHERE status = 'SENT';
CREATE TABLE retrieved_policy (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 response_id BIGINT NOT NULL REFERENCES ai_response(id),
 policy_chunk_id BIGINT NOT NULL REFERENCES policy_chunk(id),
 similarity_score DOUBLE PRECISION,
 score_metric TEXT NOT NULL,
 rank INTEGER NOT NULL CHECK (rank > 0),
 used_in_prompt BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(response_id, rank),
 UNIQUE(response_id, policy_chunk_id)
);
CREATE TABLE admin_review (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 response_id BIGINT NOT NULL REFERENCES ai_response(id),
 admin_id BIGINT NOT NULL REFERENCES admin_user(id),
 original_category TEXT NOT NULL,
 modified_category TEXT NOT NULL,
 original_intent TEXT NOT NULL,
 modified_intent TEXT NOT NULL,
 original_urgency TEXT NOT NULL CHECK (original_urgency IN ('NORMAL','CAUTION','URGENT')),
 modified_urgency TEXT NOT NULL CHECK (modified_urgency IN ('NORMAL','CAUTION','URGENT')),
 original_response TEXT NOT NULL,
 modified_response TEXT NOT NULL CHECK (length(btrim(modified_response)) > 0),
 approved BOOLEAN NOT NULL,
 use_for_training BOOLEAN NOT NULL DEFAULT FALSE,
 reviewed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 remark TEXT
);
-- feedback는 실제 전송된 답변에만 작성합니다.
CREATE TABLE feedback (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 response_id BIGINT NOT NULL UNIQUE REFERENCES ai_response(id),
 rating TEXT NOT NULL CHECK (rating IN ('SATISFIED','DISSATISFIED')),
 comment TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

