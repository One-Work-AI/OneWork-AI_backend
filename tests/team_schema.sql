-- 모든 함수는 대상 스키마를 고정합니다.
CREATE FUNCTION touch_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = cs_chatbot, pg_temp AS $$
BEGIN NEW.updated_at := clock_timestamp(); RETURN NEW; END;
$$;
DO $$
DECLARE t text;
BEGIN
 FOREACH t IN ARRAY ARRAY['customer','product','orders','shipping','payment','inquiry','ai_response'] LOOP
  EXECUTE format('CREATE TRIGGER z_touch_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION touch_updated_at()',t);
 END LOOP;
END;
$$;

CREATE FUNCTION immutable_row() RETURNS trigger
LANGUAGE plpgsql SET search_path = cs_chatbot, pg_temp AS $$
BEGIN RAISE EXCEPTION 'Historical row in % is immutable; insert a new version', TG_TABLE_NAME USING ERRCODE='23514'; END;
$$;
CREATE TRIGGER analysis_immutable BEFORE UPDATE OR DELETE ON ai_analysis FOR EACH ROW EXECUTE FUNCTION immutable_row();
CREATE TRIGGER review_immutable BEFORE UPDATE OR DELETE ON admin_review FOR EACH ROW EXECUTE FUNCTION immutable_row();
CREATE TRIGGER chunk_immutable BEFORE UPDATE OR DELETE ON policy_chunk FOR EACH ROW EXECUTE FUNCTION immutable_row();

CREATE FUNCTION guard_policy_document() RETURNS trigger
LANGUAGE plpgsql SET search_path = cs_chatbot, pg_temp AS $$
BEGIN
 IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Policy versions cannot be deleted' USING ERRCODE='23514'; END IF;
 IF (to_jsonb(NEW) - 'is_active') IS DISTINCT FROM (to_jsonb(OLD) - 'is_active') THEN
  RAISE EXCEPTION 'Insert a new policy version; only is_active may change' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER policy_immutable BEFORE UPDATE OR DELETE ON policy_document FOR EACH ROW EXECUTE FUNCTION guard_policy_document();

CREATE FUNCTION guard_review() RETURNS trigger
LANGUAGE plpgsql SET search_path = cs_chatbot, pg_temp AS $$
DECLARE r ai_response%ROWTYPE; a ai_analysis%ROWTYPE;
BEGIN
 -- 같은 답변의 검토와 전송은 행 잠금으로 직렬화합니다.
 SELECT * INTO r FROM ai_response WHERE id=NEW.response_id FOR UPDATE;
 IF NOT FOUND OR r.status='SENT' THEN
  RAISE EXCEPTION 'Review requires an existing unsent response' USING ERRCODE='23514';
 END IF;
 IF NOT EXISTS (SELECT 1 FROM admin_user WHERE id=NEW.admin_id AND is_active) THEN
  RAISE EXCEPTION 'Reviewer must be active' USING ERRCODE='23514';
 END IF;
 SELECT * INTO a FROM ai_analysis WHERE id=r.analysis_id;
 IF NEW.original_response IS DISTINCT FROM r.response_text
 OR NEW.original_category IS DISTINCT FROM a.category
 OR NEW.original_intent IS DISTINCT FROM a.intent
 OR NEW.original_urgency IS DISTINCT FROM a.urgency THEN
  RAISE EXCEPTION 'Original review fields must match the AI snapshot' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER review_before_send BEFORE INSERT ON admin_review FOR EACH ROW EXECUTE FUNCTION guard_review();

CREATE FUNCTION guard_response() RETURNS trigger
LANGUAGE plpgsql SET search_path = cs_chatbot, pg_temp AS $$
DECLARE v_review admin_review%ROWTYPE;
BEGIN
 IF TG_OP='DELETE' THEN
  IF OLD.status='SENT' THEN RAISE EXCEPTION 'Sent response is immutable' USING ERRCODE='23514'; END IF;
  RETURN OLD;
 END IF;
 IF TG_OP='UPDATE' THEN
  IF OLD.status='SENT' THEN RAISE EXCEPTION 'Sent response is immutable' USING ERRCODE='23514'; END IF;
  IF ROW(NEW.inquiry_id,NEW.analysis_id,NEW.response_text,NEW.response_language,NEW.generation_model,NEW.adapter_version,NEW.prompt_version)
    IS DISTINCT FROM ROW(OLD.inquiry_id,OLD.analysis_id,OLD.response_text,OLD.response_language,OLD.generation_model,OLD.adapter_version,OLD.prompt_version) THEN
   RAISE EXCEPTION 'Keep the original AI response; insert a new response to regenerate' USING ERRCODE='23514';
  END IF;
 END IF;
 IF NEW.status='SENT' THEN
  IF NEW.sent_automatically THEN
   IF NOT EXISTS (SELECT 1 FROM ai_analysis WHERE id=NEW.analysis_id AND auto_response_allowed) THEN
    RAISE EXCEPTION 'Automatic response not allowed' USING ERRCODE='23514';
   END IF;
   IF NEW.final_response_text IS DISTINCT FROM NEW.response_text THEN
    RAISE EXCEPTION 'Automatic final text must match the generated text' USING ERRCODE='23514';
   END IF;
   IF EXISTS (SELECT 1 FROM admin_review WHERE response_id=NEW.id) THEN
    RAISE EXCEPTION 'Reviewed responses must use manual sending' USING ERRCODE='23514';
   END IF;
  ELSE
   SELECT * INTO v_review FROM admin_review WHERE response_id=NEW.id ORDER BY id DESC LIMIT 1;
   IF NOT FOUND OR NOT v_review.approved OR v_review.modified_response IS DISTINCT FROM NEW.final_response_text THEN
    RAISE EXCEPTION 'Latest review must approve the exact final text' USING ERRCODE='23514';
   END IF;
  END IF;
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER response_guard BEFORE INSERT OR UPDATE OR DELETE ON ai_response FOR EACH ROW EXECUTE FUNCTION guard_response();

CREATE FUNCTION sync_sent_inquiry() RETURNS trigger
LANGUAGE plpgsql SET search_path = cs_chatbot, pg_temp AS $$
BEGIN
 IF NEW.status='SENT' THEN
  UPDATE inquiry SET status=CASE WHEN NEW.sent_automatically THEN 'AUTO_ANSWERED' ELSE 'COMPLETED' END WHERE id=NEW.inquiry_id;
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER response_sync AFTER INSERT OR UPDATE ON ai_response FOR EACH ROW EXECUTE FUNCTION sync_sent_inquiry();

CREATE FUNCTION guard_feedback() RETURNS trigger
LANGUAGE plpgsql SET search_path = cs_chatbot, pg_temp AS $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM ai_response WHERE id=NEW.response_id AND status='SENT') THEN
  RAISE EXCEPTION 'Feedback requires a sent response' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER feedback_guard BEFORE INSERT OR UPDATE ON feedback FOR EACH ROW EXECUTE FUNCTION guard_feedback();

CREATE VIEW chat_history AS
 SELECT q.conversation_id,q.customer_id,q.id AS inquiry_id,
 'user'::text AS role,q.content,q.created_at AS occurred_at,
 0 AS event_order,q.id AS event_id
 FROM inquiry q
 UNION ALL
 SELECT q.conversation_id,q.customer_id,q.id,
 'assistant',r.final_response_text,r.sent_at,1,r.id
 FROM ai_response r JOIN inquiry q ON q.id=r.inquiry_id
 WHERE r.status='SENT';

COMMENT ON TABLE customer IS '고객. customer는 올바른 영어 철자이며 costumer(의상 담당자)와 다릅니다.';
COMMENT ON TABLE inquiry IS '고객 문의 메시지 한 건. 같은 대화방에 여러 건 저장합니다.';
COMMENT ON COLUMN ai_response.adapter_version IS '파인튜닝 Adapter의 버전 또는 추적 가능한 식별자';
COMMENT ON COLUMN admin_review.original_response IS '검토 이전 수정본이 아닌 해당 AI 답변의 불변 생성 원문';
COMMENT ON COLUMN retrieved_policy.similarity_score IS '점수 범위와 방향은 score_metric에 따라 다릅니다. 확률이 아닙니다.';
COMMIT;
